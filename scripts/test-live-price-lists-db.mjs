// Uses the repository-pinned PGlite runtime; PGLITE_MODULE_PATH is an optional override.
const { PGlite } = await import(process.env.PGLITE_MODULE_PATH || '@electric-sql/pglite');
import { readFileSync } from 'node:fs';
import assert from 'node:assert/strict';
const db=new PGlite();
await db.exec(`create role anon; create role authenticated; create role service_role;
create schema auth; create table auth.users(id uuid primary key);
create function auth.uid() returns uuid language sql as $$ select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid $$;
create table accounts(id uuid primary key,active boolean,relationship_status text);
insert into auth.users values('00000000-0000-0000-0000-000000000001');
insert into accounts values('00000000-0000-0000-0000-000000000010',true,'current');
grant usage on schema auth to authenticated; grant execute on function auth.uid() to authenticated; grant select on accounts to authenticated;`);
await db.exec(readFileSync(new URL('../supabase/migrations/20260907120000_live_price_list_links.sql',import.meta.url),'utf8'));
const manage=async action=>(await db.query("select manage_account_price_list_link('00000000-0000-0000-0000-000000000010',$1) as token",[action])).rows[0].token;
await db.exec('set role anon');
await assert.rejects(manage('create'));
await assert.rejects(db.query('select * from account_price_list_links'));
await db.exec("reset role; set role authenticated; set request.jwt.claim.sub='00000000-0000-0000-0000-000000000001'");
const first=await manage('create'); assert.match(first,/^[0-9a-f]{64}$/);
assert.equal(await manage('create'),first);
await assert.rejects(db.exec("update account_price_list_links set revoked_at=null"));
const second=await manage('replace'); assert.notEqual(first,second);
assert.equal((await db.query('select token from account_price_list_links where token=$1',[first])).rows.length,0);
await manage('revoke');
assert.equal((await db.query('select token from account_price_list_links where revoked_at is null')).rows.length,0);
const third=await manage('create');assert.notEqual(second,third);
await db.exec("reset role; update accounts set active=false; set role authenticated");
await assert.rejects(manage('replace'));
await db.close(); console.log('Link creation/reuse, replacement, revocation, active Account checks and anonymous/write denial passed.');
